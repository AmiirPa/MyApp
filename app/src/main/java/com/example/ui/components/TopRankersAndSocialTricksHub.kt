 */
@OptIn(ExperimentalLayoutApi::class)
@Composable
fun TopRankersAndSocialTricksHub(
    initialSubjectId: String? = null,
    modifier: Modifier = Modifier
) {
    val playbooks = TopRankersPlaybookRepository.allPlaybooks
    val defaultIdx = remember(initialSubjectId) {
        if (initialSubjectId == null) 0
        else {
            val target = TopRankersPlaybookRepository.getPlaybookForSubject(initialSubjectId)
            playbooks.indexOfFirst { it.subjectId == target.subjectId }.coerceAtLeast(0)
        }
    }
    var selectedPlaybookIdx by remember(defaultIdx) { mutableIntStateOf(defaultIdx) }
    var searchQuery by remember { mutableStateOf("") }

    val filteredPlaybooks = remember(playbooks, searchQuery) {
        val q = searchQuery.trim()
        if (q.isEmpty()) playbooks
        else playbooks.filter { pb ->
            pb.subjectTitle.contains(q, ignoreCase = true) ||
                pb.bookletUnlockerSteps.any { it.contains(q, ignoreCase = true) } ||
                pb.socialMediaTricks.any { it.first.contains(q, ignoreCase = true) || it.second.contains(q, ignoreCase = true) }
        }
    }
    val currentPlaybook = filteredPlaybooks.getOrElse(selectedPlaybookIdx.coerceIn(0, (filteredPlaybooks.size - 1).coerceAtLeast(0))) {
        playbooks[selectedPlaybookIdx.coerceIn(playbooks.indices)]
    }

    Surface(
        modifier = modifier
            .fillMaxWidth()
            .testTag("top_rankers_social_tricks_hub"),
        shape = RoundedCornerShape(22.dp),
        color = MaterialTheme.colorScheme.surface,
        border = BorderStroke(1.2.dp, currentPlaybook.accentColor.copy(alpha = 0.45f)),
        tonalElevation = 2.dp
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(14.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            // 1. Header Banner (Honest, Source-Backed Label)
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    modifier = Modifier.weight(1f)
                ) {
                    Box(
                        modifier = Modifier
                            .size(48.dp)
                            .background(
                                Brush.linearGradient(
                                    listOf(
                                        currentPlaybook.accentColor.copy(alpha = 0.22f),
                                        MaterialTheme.colorScheme.secondaryContainer
                                    )
                                ),
                                CircleShape
                            ),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = Icons.Default.EmojiEvents,
                            contentDescription = null,
                            tint = currentPlaybook.accentColor,
                            modifier = Modifier.size(26.dp)
                        )
                    }
                    Spacer(modifier = Modifier.width(10.dp))
                    Column {
                        BiDiText(
                            text = "راهنمای مطالعاتی و تکنیک‌های پیشنهادی بر اساس سرفصل رسمی: ${currentPlaybook.subjectTitle}",
                            style = MaterialTheme.typography.titleSmall,
                            fontWeight = FontWeight.Black,
                            color = MaterialTheme.colorScheme.onSurface,
                            maxLines = 2
                        )
                        BiDiText(
                            text = currentPlaybook.sourceMetadata,
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            maxLines = 2
                        )
                    }
                }
            }

            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(4.dp)
                    .background(
                        Brush.linearGradient(
                            listOf(
                                currentPlaybook.accentColor.copy(alpha = 0.4f),
                                MaterialTheme.colorScheme.tertiary.copy(alpha = 0.4f)
                            )
