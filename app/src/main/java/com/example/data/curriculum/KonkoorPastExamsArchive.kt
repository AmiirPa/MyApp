    private val masterQuestionPoolBySubject: Map<String, List<QuizQuestionItem>> by lazy {
        val baseQuestions = buildList {
            addAll(examPapers.flatMap { it.questions })
            addAll(FlashcardAndQuizBank.quizQuestions)
            FlashcardAndQuizBank.allLessons.forEach { lesson ->
                val mc = lesson.miniCheck
                if (mc.options.size >= 4) {
                    val tip = lesson.goldenFormulas.firstOrNull() ?: lesson.subtitle
                    add(
                        QuizQuestionItem(
                            id = "lesson_mc_${lesson.id}",
                            subjectId = lesson.subjectId,
                            difficultyTag = "${lesson.title} (${lesson.levelBadge})",
                            questionText = mc.question,
                            options = mc.options.take(4),
                            correctOptionIndex = mc.correctIndex.coerceIn(0, 3),
